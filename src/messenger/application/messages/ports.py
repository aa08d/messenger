from typing import Protocol
from uuid import UUID

from messenger.domain.common.value_objects.identity import ChatId, MessageId, UserId
from messenger.domain.messages import Message, Reaction


class MessageRepository(Protocol):
    async def prior_request(self, chat: ChatId, author: UserId, request: UUID) -> tuple[int, str | None] | None: ...
    async def visible(self, message_id: MessageId, viewer: UserId) -> Message: ...
    async def add(self, message: Message, request: UUID, digest: str, details: dict) -> None: ...
    async def content_details(self, message_id: MessageId) -> dict: ...
    async def update_content(self, message: Message) -> None: ...
    async def update_pin(self, message: Message) -> None: ...
    async def hide(self, message_id: MessageId, viewer: UserId) -> None: ...
    async def delete(self, message_id: MessageId) -> None: ...
    async def react(self, message_id: MessageId, viewer: UserId, reaction: Reaction | None) -> None: ...
